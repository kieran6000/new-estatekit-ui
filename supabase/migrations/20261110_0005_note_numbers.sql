-- Every to-do and note gets a short number, so the team can say "#42" and the
-- WhatsApp link is leads.estatekit.co/t/42. Existing ones are numbered in
-- the order they were made. Add-only.
alter table public.client_notes
  add column if not exists num bigint generated by default as identity;

-- Number the existing ones oldest first (identity filled them in table order).
with ordered as (
  select id, row_number() over (order by created_at, id) as n from public.client_notes
)
update public.client_notes c set num = o.n from ordered o where o.id = c.id;
select setval(pg_get_serial_sequence('public.client_notes', 'num'), coalesce((select max(num) from public.client_notes), 0) + 1, false);

create unique index if not exists client_notes_num on public.client_notes (num);
